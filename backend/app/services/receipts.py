"""Payment receipt PDF (fpdf2, pure Python — small enough for a serverless bundle)."""
from fpdf import FPDF

from app.models import Lease, Organization, Payment, Property, Tenant, Unit


def money(cents: int, currency: str = "USD") -> str:
    sign = "-" if cents < 0 else ""
    symbol = "$" if currency == "USD" else f"{currency} "
    return f"{sign}{symbol}{abs(cents) / 100:,.2f}"


def _latin1(text: str) -> str:
    # Core PDF fonts are Latin-1 only.
    return text.replace("—", "-").replace("–", "-").encode("latin-1", "replace").decode("latin-1")


def receipt_pdf(
    org: Organization,
    payment: Payment,
    lease: Lease,
    unit: Unit,
    prop: Property,
    tenant: Tenant | None,
    balance_after: int,
) -> bytes:
    pdf = FPDF(format="Letter")
    pdf.set_margins(20, 20, 20)
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 20)
    pdf.set_text_color(164, 80, 42)  # Strata copper
    pdf.cell(0, 10, _latin1(org.name), new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(15, 23, 42)
    pdf.set_font("Helvetica", "", 11)
    pdf.cell(0, 6, "Payment receipt", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(6)

    rows = [
        ("Receipt #", payment.receipt_number),
        ("Date received", payment.received_on.strftime("%B %d, %Y")),
        ("Received from", f"{tenant.first_name} {tenant.last_name}" if tenant else "Tenant"),
        ("Property", f"{prop.name} - {unit.name}"),
        ("Address", f"{prop.address_line1}, {prop.city}, {prop.state} {prop.postal_code}"),
        ("Payment method", payment.method.replace("_", " ").title()),
    ]
    if payment.reference:
        rows.append(("Reference", payment.reference))

    for label, value in rows:
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(45, 8, _latin1(label))
        pdf.set_font("Helvetica", "", 10)
        pdf.cell(0, 8, _latin1(str(value)), new_x="LMARGIN", new_y="NEXT")

    pdf.ln(4)
    pdf.set_draw_color(203, 213, 225)
    pdf.line(20, pdf.get_y(), 196, pdf.get_y())
    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 14)
    pdf.cell(45, 10, "Amount paid")
    pdf.cell(0, 10, money(payment.amount_cents, org.currency), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(45, 8, "Balance after payment")
    pdf.cell(0, 8, money(balance_after, org.currency), new_x="LMARGIN", new_y="NEXT")

    pdf.ln(12)
    pdf.set_text_color(100, 116, 139)
    pdf.set_font("Helvetica", "", 8)
    pdf.cell(0, 5, "Generated by Proppros", new_x="LMARGIN", new_y="NEXT")
    return bytes(pdf.output())
